"""Types of the API's structured error contract."""

from enum import Enum

from pydantic import BaseModel


class ErrorCode(str, Enum):
    """Códigos estables que el frontend puede usar para identificar errores."""

    CONNECTION = "CONNECTION"
    INTERNAL = "INTERNAL"
    NO_MEDICAL_CLAIMS = "NO_MEDICAL_CLAIMS"
    ANALYSIS_SAVE_FAILED = "ANALYSIS_SAVE_FAILED"
    SERVICE_UNAVAILABLE = "SERVICE_UNAVAILABLE"
    URL_EXTRACTION = "URL_EXTRACTION"
    INVALID_FILE = "INVALID_FILE"
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    FILE_EXTRACTION = "FILE_EXTRACTION"
    INVALID_ANALYSIS_ID = "INVALID_ANALYSIS_ID"
    ANALYSIS_NOT_FOUND = "ANALYSIS_NOT_FOUND"
    EVIDENCE_SEARCH_NOT_FOUND = "EVIDENCE_SEARCH_NOT_FOUND"
    ANALYSIS_FETCH_FAILED = "ANALYSIS_FETCH_FAILED"
    ANALYSIS_DELETE_FAILED = "ANALYSIS_DELETE_FAILED"
    ANALYSIS_NOT_RETRYABLE = "ANALYSIS_NOT_RETRYABLE"
    ANALYSIS_RETRY_FAILED = "ANALYSIS_RETRY_FAILED"
    ANALYSIS_NOT_REANALYZABLE = "ANALYSIS_NOT_REANALYZABLE"
    ANALYSIS_REANALYZE_FAILED = "ANALYSIS_REANALYZE_FAILED"
    FEEDBACK_NOT_ALLOWED = "FEEDBACK_NOT_ALLOWED"
    FEEDBACK_ALREADY_SUBMITTED = "FEEDBACK_ALREADY_SUBMITTED"
    FEEDBACK_SAVE_FAILED = "FEEDBACK_SAVE_FAILED"
    ANALYSIS_NOT_SHAREABLE = "ANALYSIS_NOT_SHAREABLE"
    SHARE_FAILED = "SHARE_FAILED"
    SHARED_REPORT_NOT_FOUND = "SHARED_REPORT_NOT_FOUND"
    HISTORY_FETCH_FAILED = "HISTORY_FETCH_FAILED"
    HISTORY_DELETE_FAILED = "HISTORY_DELETE_FAILED"
    DASHBOARD_FETCH_FAILED = "DASHBOARD_FETCH_FAILED"
    CONTACT_SEND_FAILED = "CONTACT_SEND_FAILED"
    PLAN_REQUIRED = "PLAN_REQUIRED"
    ALLOWANCE_EXHAUSTED = "ALLOWANCE_EXHAUSTED"
    TEXT_TOO_LONG_FOR_PLAN = "TEXT_TOO_LONG_FOR_PLAN"
    ALREADY_SUBSCRIBED = "ALREADY_SUBSCRIBED"
    BILLING_ACCOUNT_NOT_FOUND = "BILLING_ACCOUNT_NOT_FOUND"
    BILLING_UNAVAILABLE = "BILLING_UNAVAILABLE"
    BILLING_FETCH_FAILED = "BILLING_FETCH_FAILED"
    INVALID_WEBHOOK = "INVALID_WEBHOOK"
    VALIDATION = "VALIDATION"
    RATE_LIMIT = "RATE_LIMIT"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    INVALID_TOKEN = "INVALID_TOKEN"
    EXPIRED_TOKEN = "EXPIRED_TOKEN"
    AUTH_MISCONFIGURED = "AUTH_MISCONFIGURED"


class ErrorDetail(BaseModel):
    """Forma del campo `detail` que se envía en HTTPException."""

    code: ErrorCode
    message: str


class ErrorResponse(BaseModel):
    """Cuerpo completo de un error: {"detail": ErrorDetail}."""

    detail: ErrorDetail
